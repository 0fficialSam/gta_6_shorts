"""
Run this ONCE to fix ImageMagick not being found by MoviePy on Windows.
Usage: python fix_imagemagick.py
"""
import os
import glob
import subprocess
import sys

def find_imagemagick():
    """Search common install locations for ImageMagick."""
    print("Searching for ImageMagick...")

    # Try 'where magick' command first
    try:
        result = subprocess.run(["where", "magick"], capture_output=True, text=True)
        if result.returncode == 0:
            path = result.stdout.strip().splitlines()[0]
            print(f"  Found via PATH: {path}")
            return path
    except:
        pass

    # Common Windows install locations
    search_paths = [
        r"C:\Program Files\ImageMagick*\magick.exe",
        r"C:\Program Files (x86)\ImageMagick*\magick.exe",
        r"C:\ImageMagick*\magick.exe",
        os.path.expanduser(r"~\ImageMagick*\magick.exe"),
    ]

    for pattern in search_paths:
        matches = glob.glob(pattern)
        if matches:
            print(f"  Found: {matches[0]}")
            return matches[0]

    return None


def fix_moviepy(magick_path: str):
    """Patch MoviePy's config to use the correct ImageMagick path."""
    try:
        import moviepy.config as cfg
        config_file = cfg.__file__
        print(f"\nMoviePy config: {config_file}")
    except ImportError:
        print("MoviePy not installed! Run: pip install moviepy")
        sys.exit(1)

    # Method 1: Set environment variable (works immediately)
    os.environ["IMAGEMAGICK_BINARY"] = magick_path
    print(f"Set IMAGEMAGICK_BINARY = {magick_path}")

    # Method 2: Write to MoviePy config file (permanent)
    try:
        import moviepy.config_defaults as defaults
        defaults.IMAGEMAGICK_BINARY = magick_path
        print("Patched MoviePy config_defaults")
    except:
        pass

    # Method 3: Create/update moviepy config file
    config_dir = os.path.dirname(config_file)
    config_path = os.path.join(config_dir, "config.py")

    config_content = f'''# Auto-generated by fix_imagemagick.py
IMAGEMAGICK_BINARY = r"{magick_path}"
FFMPEG_BINARY = "ffmpeg"
'''
    with open(config_path, "w") as f:
        f.write(config_content)
    print(f"Written to: {config_path}")

    # Test it works
    print("\nTesting ImageMagick...")
    try:
        result = subprocess.run([magick_path, "--version"], capture_output=True, text=True)
        if result.returncode == 0:
            version = result.stdout.splitlines()[0]
            print(f"  OK! {version}")
        else:
            print(f"  Warning: {result.stderr}")
    except Exception as e:
        print(f"  Error: {e}")


def test_textclip():
    """Test that MoviePy TextClip works."""
    print("\nTesting MoviePy TextClip...")
    try:
        import moviepy.config as mpy_config
        mpy_config.change_settings({"IMAGEMAGICK_BINARY": os.environ.get("IMAGEMAGICK_BINARY", "magick")})
        from moviepy.editor import TextClip
        clip = TextClip("TEST", fontsize=50, color="white")
        print("  SUCCESS! TextClip works perfectly.")
        clip.close()
    except Exception as e:
        print(f"  Failed: {e}")
        print("\n  Try running the script with your magick.exe path:")
        print("  python fix_imagemagick.py C:\\Program Files\\ImageMagick-7.x.x\\magick.exe")


if __name__ == "__main__":
    print("=" * 50)
    print("  ImageMagick + MoviePy Fixer for Windows")
    print("=" * 50)

    # Allow manual path as argument
    if len(sys.argv) > 1:
        magick_path = sys.argv[1]
        print(f"Using provided path: {magick_path}")
    else:
        magick_path = find_imagemagick()

    if not magick_path:
        print("\nImageMagick NOT FOUND!")
        print("Please provide the path manually:")
        print("  python fix_imagemagick.py \"C:\\Program Files\\ImageMagick-7.x.x\\magick.exe\"")
        print("\nOr download from: https://imagemagick.org/script/download.php#windows")
        sys.exit(1)

    fix_moviepy(magick_path)
    test_textclip()

    print("\n" + "=" * 50)
    print("DONE! Now run: python main.py --test --no-upload")
    print("=" * 50)
